/* Presentation only: concise Android-style titles and body for Web Push.
 * Does not affect event detection, stored event keys, delivery deduplication,
 * device selection, or case navigation.
 */
const TITLES=Object.freeze({
 blanko:"🧾 Blanko Tilang Terbit",
 dispute:"⚠️ Pelanggaran Tersanggah",
 shipping_printed:"🖨️ Surat ETLE Tercetak",
 shipping_processing:"🚚 Surat Dalam Proses Pengiriman",
 shipping_delivered:"✅ Surat Berhasil Terkirim",
 shipping_failed:"⚠️ Pengiriman Surat Gagal",
 shipping_returned:"↩️ Surat Dikembalikan"
});
export function compactNotification(event){
 const title=TITLES[event?.event_type]||String(event?.title||"G-Smart · ETLE");
 const source=String(event?.body||"");
 // Preserve every plate exactly as delivered; remove redundant label and
 // separator only for messages generated by the G-Smart production sender.
 const match=source.match(/^TNKB:\s*(.*?)\s*·\s*([\s\S]*)$/i);
 const body=match?match[1].trim()+" • "+match[2].trim().replace(/\.$/,""):source;
 return {title,body};
}
